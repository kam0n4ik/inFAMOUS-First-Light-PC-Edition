"""Generates src/runtime/gpu/gcn/gcn_opcode_names.inc: the GCN (Sea Islands, the PS4's) opcode of each encoding with
its mnemonic, read as data from the oracle's tables (third_party/shadPS4/src/shader_recompiler/frontend/opcodes.h,
the per-encoding enums). Run once when the table changes; the output is committed.

    python tools/gcn/gen_opcode_names.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "third_party" / "shadPS4" / "src" / "shader_recompiler" / "frontend" / "opcodes.h"
OUT = ROOT / "src" / "runtime" / "gpu" / "gcn" / "gcn_opcode_names.inc"

# the oracle's enum -> SecondSonPC's Format enumerator (gcn_decoder.h)
ENUMS = {
    "OpcodeSOP2": "Sop2", "OpcodeSOPK": "Sopk", "OpcodeSOP1": "Sop1", "OpcodeSOPC": "Sopc", "OpcodeSOPP": "Sopp",
    "OpcodeSMRD": "Smrd", "OpcodeVOP2": "Vop2", "OpcodeVOP3": "Vop3", "OpcodeVOP1": "Vop1", "OpcodeVOPC": "Vopc",
    "OpcodeVINTRP": "Vintrp", "OpcodeDS": "Ds", "OpcodeMUBUF": "Mubuf", "OpcodeMTBUF": "Mtbuf", "OpcodeMIMG": "Mimg",
    "OpcodeEXP": "Exp",
}


def main():
    text = SRC.read_text(encoding="utf-8")
    rows = []
    for enum, fmt in ENUMS.items():
        m = re.search(r"enum class " + enum + r" : u32 \{(.*?)\n\};", text, re.S)
        if m is None:
            raise SystemExit(f"{enum} not found in {SRC}")
        names = {}
        for line in m.group(1).splitlines():
            line = line.split("//")[0].strip().rstrip(",")
            mm = re.fullmatch(r"([A-Z0-9_]+)\s*=\s*(.+)", line)
            if not mm or mm.group(1).startswith("OP_RANGE"):
                continue
            value = mm.group(2).strip()
            try:
                v = int(value, 0)
            except ValueError:  # (an expression of an earlier name: "X + 1")
                expr = re.fullmatch(r"([A-Z0-9_]+)\s*\+\s*(\d+)", value)
                if expr is None or expr.group(1) not in names:
                    raise SystemExit(f"{enum}: cannot evaluate {line}")
                v = names[expr.group(1)] + int(expr.group(2))
            names[mm.group(1)] = v
        for name, v in names.items():
            rows.append((fmt, v, name.lower()))
    rows.sort(key=lambda r: (list(ENUMS.values()).index(r[0]), r[1]))
    lines = [
        "// GENERATED by tools/gcn/gen_opcode_names.py from the oracle's opcode tables - do not edit.",
        "// {Format, opcode, mnemonic}",
    ]
    lines += [f'{{Format::{f}, {v}, "{n}"}},' for f, v, n in rows]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(rows)} opcodes -> {OUT}")


if __name__ == "__main__":
    main()

"""Static recompilation PoC, steps 2-3 (IR -> transformations -> C++ -> native object).

Input: the raw P-code of whole functions (pcode_dump.py, Ghidra SLEIGH x86-64 = the decoder and the lifter).
Output: one C++ file with a System V entry per function, `recomp_<rva>`, compiled by clang into a native object; the
CFG is kept as labels (one per guest instruction, one per internal P-code branch target) and gotos; clang -O2 turns
the byte-array register file into SSA values.

Model (docs/NATIVE_ENGINE_RECONSTRUCTION.md §6):
  - register space -> a byte array R[] at SLEIGH's register offsets (sub-registers alias like the hardware's);
  - unique space   -> a byte array U[] (P-code temporaries);
  - ram space      -> guest memory (guest address = host address); a ram varnode written in the instruction (an
                      absolute or RIP-relative operand) is eboot-relative in Ghidra and is rebased on recomp_image_base;
  - RSP            -> a private stack inside the generated function (functions with stack arguments are refused);
  - CALL to a guest function -> a real System V call of image_base + target with RDI..R9, RAX/RDX back;
  - LOCK-prefixed CMPXCHG -> one __atomic_compare_exchange (SLEIGH lifts it as a plain load/compare/store between
                      CALLOTHER LOCK/UNLOCK markers: emitting those ops as they are would drop the atomicity);
  - any other CALLOTHER, floating-point op, indirect branch/call or a branch out of the function -> refused (listed).

usage: py -I -X utf8 pcode2c.py <pcode.json> <out.cpp> [--report <report.txt>]
"""
import json
import re
import sys

INT_OPS = {
    "INT_ADD": "+", "INT_SUB": "-", "INT_AND": "&", "INT_OR": "|", "INT_XOR": "^", "INT_MULT": "*",
}
CMP_OPS = {"INT_EQUAL": "==", "INT_NOTEQUAL": "!="}
UNSIGNED_CMP = {"INT_LESS": "<", "INT_LESSEQUAL": "<="}
SIGNED_CMP = {"INT_SLESS": "<", "INT_SLESSEQUAL": "<="}

PRELUDE = r'''// Generated by tools/native-reconstruction/recomp/pcode2c.py from Ghidra's P-code of the eboot - do not edit.
// Static recompilation PoC (docs/NATIVE_ENGINE_RECONSTRUCTION.md §6): every guest instruction is a label with its
// P-code as C++ statements over a byte-array register file.
#include <cstdint>
#include <cstring>
typedef std::uint8_t u8;
typedef std::uint64_t u64;
typedef std::int64_t s64;
#define SYSV __attribute__((sysv_abi))
extern "C" __declspec(dllexport) u64 recomp_image_base = 0;
static inline u64 ld(const u8* b, u64 off, int n) { u64 v = 0; std::memcpy(&v, b + off, n); return v; }
static inline void st(u8* b, u64 off, int n, u64 v) { std::memcpy(b + off, &v, n); }
static inline u64 mload(u64 a, int n) { u64 v = 0; std::memcpy(&v, reinterpret_cast<const void*>(a), n); return v; }
static inline void mstore(u64 a, int n, u64 v) { std::memcpy(reinterpret_cast<void*>(a), &v, n); }
static inline u64 mask(int n) { return n >= 8 ? ~0ull : ((1ull << (8 * n)) - 1); }
static inline s64 sx(u64 v, int n) { return n >= 8 ? static_cast<s64>(v) : static_cast<s64>(v << (64 - 8 * n)) >> (64 - 8 * n); }
static inline u64 carry(u64 a, u64 b, int n) { return ((a & mask(n)) + (b & mask(n))) > mask(n) || (n == 8 && a + b < a); }
static inline u64 scarry(u64 a, u64 b, int n) { s64 x = sx(a, n), y = sx(b, n); s64 r = sx((a + b) & mask(n), n); return (x >= 0 && y >= 0 && r < 0) || (x < 0 && y < 0 && r >= 0); }
static inline u64 sborrow(u64 a, u64 b, int n) { s64 x = sx(a, n), y = sx(b, n); s64 r = sx((a - b) & mask(n), n); return (x >= 0 && y < 0 && r < 0) || (x < 0 && y >= 0 && r >= 0); }
typedef SYSV u64 (*GuestFn)(u64, u64, u64, u64, u64, u64);
'''


class Unsupported(Exception):
    pass


class Emitter:
    def __init__(self, func, registers):
        self.f = func
        self.reg_names = registers  # "off:size" -> name
        self.reg_off = {}
        for k, name in registers.items():
            off, size = (int(x) for x in k.split(":"))
            self.reg_off[name] = (off, size)
        self.entry = func["entry"]
        self.end = func["entry"] + func["size"]
        self.addrs = {i["addr"] for i in func["instructions"]}
        self.lines = []
        self.stats = {"instructions": len(func["instructions"]), "pcode": 0, "atomics": 0, "calls": 0,
                      "labels": 0}

    def reg(self, name):
        if name not in self.reg_off:
            raise Unsupported("register %s not in the dump" % name)
        return self.reg_off[name]

    def read(self, v):
        space, off, size = v
        if size > 8:
            raise Unsupported("a %d-byte value (vector) read" % size)
        if space == "const":
            return "(0x%xull & mask(%d))" % (off & 0xFFFFFFFFFFFFFFFF, size)
        if space == "register":
            return "ld(R, %d, %d)" % (off, size)
        if space == "unique":
            return "ld(U, %d, %d)" % (off, size)
        if space == "ram":
            return "mload(recomp_image_base + 0x%xull, %d)" % (off, size)
        raise Unsupported("space %s" % space)

    def write(self, v, expr):
        space, off, size = v
        if size > 8:
            raise Unsupported("a %d-byte value (vector) write" % size)
        if space == "register":
            return "st(R, %d, %d, %s);" % (off, size, expr)
        if space == "unique":
            return "st(U, %d, %d, %s);" % (off, size, expr)
        if space == "ram":
            return "mstore(recomp_image_base + 0x%xull, %d, %s);" % (off, size, expr)
        raise Unsupported("write to space %s" % space)

    def target(self, ins, idx, v):
        space, off, _ = v
        if space == "ram":
            if off not in self.addrs:
                raise Unsupported("branch out of the function to %#x" % off)
            return "L_%x" % off
        if space == "const":
            rel = off if off < (1 << 63) else off - (1 << 64)
            return "P_%x_%d" % (ins["addr"], idx + rel)
        raise Unsupported("branch target space %s" % space)

    def emit_lock_cmpxchg(self, ins, ops, lock_at, unlock_at):
        # address ops before the LOAD, then one atomic CAS
        region = ops[lock_at + 1:unlock_at]
        load = next((o for o in region if o["op"] == "LOAD"), None)
        if load is None or "CMPXCHG" not in ins["mnemonic"].upper():
            raise Unsupported("LOCK region of %s" % ins["mnemonic"])
        n = load["out"][2]
        out = []
        for o in region:
            if o is load:
                break
            out.append(self.op(ins, -1, o))
        m = re.search(r",\s*([A-Z0-9]+)\s*$", ins["text"])
        if m is None:
            raise Unsupported("CMPXCHG source register in '%s'" % ins["text"])
        src = self.reg(m.group(1))
        acc = self.reg({8: "RAX", 4: "EAX", 2: "AX", 1: "AL"}[n])
        rax = self.reg("RAX")
        zf = self.reg("ZF")
        ty = {8: "u64", 4: "std::uint32_t", 2: "std::uint16_t", 1: "u8"}[n]
        out.append("{ %s expected = static_cast<%s>(ld(R, %d, %d)); const %s desired = static_cast<%s>(ld(R, %d, %d)); "
                   "const bool ok = __atomic_compare_exchange_n(reinterpret_cast<%s*>(%s), &expected, desired, false, "
                   "__ATOMIC_SEQ_CST, __ATOMIC_SEQ_CST); st(R, %d, 1, ok ? 1 : 0); if (!ok) { %s } }"
                   % (ty, ty, acc[0], n, ty, ty, src[0], n, ty, self.read(load["in"][1]), zf[0],
                      ("st(R, %d, 8, static_cast<u64>(expected));" % rax[0]) if n == 4 else
                      ("st(R, %d, %d, static_cast<u64>(expected));" % (acc[0], n))))
        self.stats["atomics"] += 1
        return out

    def op(self, ins, idx, o):
        name = o["op"]
        out = o["out"]
        ins_ = o["in"]
        n = out[2] if out else 0
        if name == "COPY":
            return self.write(out, self.read(ins_[0]))
        if name in INT_OPS:
            return self.write(out, "((%s %s %s) & mask(%d))" % (self.read(ins_[0]), INT_OPS[name], self.read(ins_[1]), n))
        if name in CMP_OPS:
            m = ins_[0][2]
            return self.write(out, "(((%s & mask(%d)) %s (%s & mask(%d))) ? 1 : 0)"
                              % (self.read(ins_[0]), m, CMP_OPS[name], self.read(ins_[1]), m))
        if name in UNSIGNED_CMP:
            m = ins_[0][2]
            return self.write(out, "(((%s & mask(%d)) %s (%s & mask(%d))) ? 1 : 0)"
                              % (self.read(ins_[0]), m, UNSIGNED_CMP[name], self.read(ins_[1]), m))
        if name in SIGNED_CMP:
            m = ins_[0][2]
            return self.write(out, "((sx(%s, %d) %s sx(%s, %d)) ? 1 : 0)"
                              % (self.read(ins_[0]), m, SIGNED_CMP[name], self.read(ins_[1]), m))
        if name == "INT_LEFT":
            return self.write(out, "((%s) >= %d ? 0 : ((%s << (%s)) & mask(%d)))"
                              % (self.read(ins_[1]), 8 * n, self.read(ins_[0]), self.read(ins_[1]), n))
        if name == "INT_RIGHT":
            return self.write(out, "((%s) >= %d ? 0 : (((%s) & mask(%d)) >> (%s)))"
                              % (self.read(ins_[1]), 8 * ins_[0][2], self.read(ins_[0]), ins_[0][2], self.read(ins_[1])))
        if name == "INT_SRIGHT":
            return self.write(out, "(static_cast<u64>(sx(%s, %d) >> ((%s) >= %d ? %d : (%s))) & mask(%d))"
                              % (self.read(ins_[0]), ins_[0][2], self.read(ins_[1]), 8 * ins_[0][2],
                                 8 * ins_[0][2] - 1, self.read(ins_[1]), n))
        if name == "INT_NEGATE":
            return self.write(out, "((~%s) & mask(%d))" % (self.read(ins_[0]), n))
        if name == "INT_2COMP":
            return self.write(out, "((0 - %s) & mask(%d))" % (self.read(ins_[0]), n))
        if name == "INT_ZEXT":
            return self.write(out, "(%s & mask(%d))" % (self.read(ins_[0]), ins_[0][2]))
        if name == "INT_SEXT":
            return self.write(out, "(static_cast<u64>(sx(%s, %d)) & mask(%d))" % (self.read(ins_[0]), ins_[0][2], n))
        if name == "INT_CARRY":
            return self.write(out, "carry(%s, %s, %d)" % (self.read(ins_[0]), self.read(ins_[1]), ins_[0][2]))
        if name == "INT_SCARRY":
            return self.write(out, "scarry(%s, %s, %d)" % (self.read(ins_[0]), self.read(ins_[1]), ins_[0][2]))
        if name == "INT_SBORROW":
            return self.write(out, "sborrow(%s, %s, %d)" % (self.read(ins_[0]), self.read(ins_[1]), ins_[0][2]))
        if name == "BOOL_NEGATE":
            return self.write(out, "(%s ? 0 : 1)" % self.read(ins_[0]))
        if name in ("BOOL_AND", "BOOL_OR", "BOOL_XOR"):
            sym = {"BOOL_AND": "&", "BOOL_OR": "|", "BOOL_XOR": "^"}[name]
            return self.write(out, "((%s %s %s) & 1)" % (self.read(ins_[0]), sym, self.read(ins_[1])))
        if name == "POPCOUNT":
            return self.write(out, "static_cast<u64>(__builtin_popcountll(%s & mask(%d)))" % (self.read(ins_[0]), ins_[0][2]))
        if name == "SUBPIECE":
            src = ins_[0]
            shift = ins_[1][1]
            if src[2] > 8:  # a piece of a vector register: read the bytes
                space = {"register": "R", "unique": "U"}.get(src[0])
                if space is None:
                    raise Unsupported("SUBPIECE of %s" % src[0])
                return self.write(out, "ld(%s, %d, %d)" % (space, src[1] + shift, n))
            return self.write(out, "((%s >> %d) & mask(%d))" % (self.read(src), 8 * shift, n))
        if name == "PIECE":
            lo = ins_[1][2]
            return self.write(out, "((((%s) << %d) | (%s)) & mask(%d))" % (self.read(ins_[0]), 8 * lo, self.read(ins_[1]), n))
        if name == "LOAD":
            return self.write(out, "mload(%s, %d)" % (self.read(ins_[1]), n))
        if name == "STORE":
            return "mstore(%s, %d, %s);" % (self.read(ins_[1]), ins_[2][2], self.read(ins_[2]))
        if name == "BRANCH":
            return "goto %s;" % self.target(ins, idx, ins_[0])
        if name == "CBRANCH":
            return "if (%s) goto %s;" % (self.read(ins_[1]), self.target(ins, idx, ins_[0]))
        if name == "RETURN":
            return "return ld(R, %d, 8);" % self.reg("RAX")[0]
        if name == "CALL":
            space, off, _ = ins_[0]
            if space != "ram":
                raise Unsupported("CALL to %s" % space)
            self.stats["calls"] += 1
            r = {k: self.reg(k)[0] for k in ("RDI", "RSI", "RDX", "RCX", "R8", "R9", "RAX", "RSP")}
            # the P-code before CALL pushed the return address; the callee's RET would pop it
            return ("st(R, %d, 8, reinterpret_cast<GuestFn>(recomp_image_base + 0x%xull)(ld(R, %d, 8), ld(R, %d, 8), "
                    "ld(R, %d, 8), ld(R, %d, 8), ld(R, %d, 8), ld(R, %d, 8))); st(R, %d, 8, ld(R, %d, 8) + 8);"
                    % (r["RAX"], off, r["RDI"], r["RSI"], r["RDX"], r["RCX"], r["R8"], r["R9"], r["RSP"], r["RSP"]))
        raise Unsupported(name)

    def run(self):
        f = self.f
        rsp = self.reg("RSP")[0]
        args = ("RDI", "RSI", "RDX", "RCX", "R8", "R9")
        regmax = max(off + size for off, size in self.reg_off.values()) + 64
        umax = 0
        for ins in f["instructions"]:
            for o in ins["pcode"]:
                for v in [o["out"]] + o["in"]:
                    if v and v[0] == "unique":
                        umax = max(umax, v[1] + v[2])
        L = self.lines
        L.append('extern "C" __declspec(dllexport) SYSV u64 recomp_%x(u64 rdi, u64 rsi, u64 rdx, u64 rcx, u64 r8, u64 r9) {'
                 % self.entry)
        L.append("    alignas(16) u8 R[%d] = {};" % regmax)
        L.append("    alignas(16) u8 U[%d];" % (umax + 16))
        L.append("    alignas(16) u8 stack[1024];  // the function's own stack (pushes, locals); stack arguments: refused")
        for a, v in zip(args, ("rdi", "rsi", "rdx", "rcx", "r8", "r9")):
            L.append("    st(R, %d, 8, %s);" % (self.reg(a)[0], v))
        L.append("    st(R, %d, 8, reinterpret_cast<u64>(stack) + sizeof(stack) - 8);  // [rsp] = (return address)" % rsp)
        L.append("    goto L_%x;" % self.entry)
        for ins in f["instructions"]:
            ops = ins["pcode"]
            self.stats["pcode"] += len(ops)
            L.append("L_%x:  // %s" % (ins["addr"], ins["text"]))
            self.stats["labels"] += 1
            # P-code-internal branch targets of this instruction
            internal = set()
            for i, o in enumerate(ops):
                if o["op"] in ("BRANCH", "CBRANCH") and o["in"][0][0] == "const":
                    off = o["in"][0][1]
                    rel = off if off < (1 << 63) else off - (1 << 64)
                    internal.add(i + rel)
            lock_at = next((i for i, o in enumerate(ops) if o["op"] == "CALLOTHER"
                            and f["callother"].get(str(o["in"][0][1])) == "LOCK"), None)
            i = 0
            while i < len(ops):
                if i in internal:
                    L.append("P_%x_%d:;" % (ins["addr"], i))
                o = ops[i]
                if lock_at is not None and i == lock_at:
                    unlock_at = next(j for j in range(i + 1, len(ops)) if ops[j]["op"] == "CALLOTHER"
                                     and f["callother"].get(str(ops[j]["in"][0][1])) == "UNLOCK")
                    for s in self.emit_lock_cmpxchg(ins, ops, i, unlock_at):
                        L.append("    " + s)
                    i = unlock_at + 1
                    continue
                if o["op"] == "CALLOTHER":
                    raise Unsupported("CALLOTHER %s in %s" % (f["callother"].get(str(o["in"][0][1])), ins["text"]))
                L.append("    " + self.op(ins, i, o))
                i += 1
            if len(ops) in internal:
                L.append("P_%x_%d:;" % (ins["addr"], len(ops)))
            # fall through to the next instruction
            nxt = ins["addr"] + ins["len"]
            if nxt in self.addrs:
                L.append("    goto L_%x;" % nxt)
            else:
                L.append("    return ld(R, %d, 8);  // end of the body" % self.reg("RAX")[0])
        L.append("}")
        return "\n".join(L)


def main():
    data = json.load(open(sys.argv[1], encoding="utf-8"))
    out = sys.argv[2]
    report_path = sys.argv[sys.argv.index("--report") + 1] if "--report" in sys.argv else None
    parts = [PRELUDE]
    report = []
    for f in data["functions"]:
        e = Emitter(f, data["registers"])
        try:
            code = e.run()
        except Unsupported as x:
            report.append("%x: REFUSED - %s (%d instructions)" % (f["entry"], x, len(f["instructions"])))
            continue
        parts.append(code)
        s = e.stats
        report.append("%x: generated - %d instructions, %d P-code ops, %d labels, %d atomic CAS, %d guest calls"
                      % (f["entry"], s["instructions"], s["pcode"], s["labels"], s["atomics"], s["calls"]))
    open(out, "w", encoding="utf-8").write("\n\n".join(parts) + "\n")
    text = "\n".join(report)
    print(text)
    if report_path:
        open(report_path, "w", encoding="utf-8").write(text + "\n")


if __name__ == "__main__":
    main()

"""The binding table of a game on the shared runtime (core/src/loader/generated/import_table_<title>.inc).

The table lists every import of eboot.bin, libc.prx and libSceFios2.prx, keyed exactly like the game imports it
(core/src/loader/bindings.h, ImportInfo). The rows of the modules both games share (libc.prx and libSceFios2.prx are
byte-identical in CUSA00004 and CUSA00897) are taken from Second Son's table; the eboot's rows are rebuilt from the
eboot itself, so a row exists for every import this eboot has and for no other.

    python -I tools/gen_import_table.py <eboot.bin> <reference import_table.inc> <aerolib.inl> <out.inc>
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ps4elf import Image  # noqa: E402

ROW = re.compile(r'\{"([^"]+)", "([^"]+)", "([^"]+)", "([^"]*)", Kind::(\w+), "([^"]*)", ([\w|]+), Phase0::(\w+)\},')

# The subsystem column for libraries Second Son's table does not have (only a label for logs and reports).
NEW_SUBSYSTEMS = {
    'libSceJson2': 'JSON (NP Web API)',
    'libSceNpScore': 'PSN (leaderboards)',
    'libSceNpTus': 'PSN (title user storage)',
    'libSceNpWebApi': 'PSN (Web API)',
    'libSceRtc': 'Clock (RTC)',
}


def main(eboot, reference, aerolib, out):
    names = {}
    for line in open(aerolib, encoding='utf-8', errors='replace'):
        m = re.match(r'\s*STUB\(\s*"([^"]+)"\s*,\s*(\w+)', line)
        if m:
            names[m.group(1)] = m.group(2)
    shad_root = os.path.join(os.path.dirname(aerolib), '..', 'libraries')
    shad_text = []
    for root, _, files in os.walk(shad_root):
        for f in files:
            if f.endswith('.cpp'):
                shad_text.append(open(os.path.join(root, f), encoding='utf-8', errors='replace').read())
    shad_text = '\n'.join(shad_text)

    ref_rows = []
    for line in open(reference, encoding='utf-8'):
        m = ROW.match(line.strip())
        if m:
            ref_rows.append(list(m.groups()))
    by_key = {(r[0], r[1], r[2]): r for r in ref_rows}
    subsystem_of_lib = {}
    for r in ref_rows:
        subsystem_of_lib.setdefault(r[1], r[5])

    img = Image(eboot).analyze()
    eboot_imports = {(nid, lib, mod): kind for nid, lib, mod, kind in img['imports']}

    rows = []
    for r in ref_rows:
        bits = set(r[6].split('|'))
        bits.discard('kEboot')
        if (r[0], r[1], r[2]) in eboot_imports:
            bits.add('kEboot')
        if not bits:
            continue
        order = [b for b in ('kEboot', 'kFios2', 'kLibc') if b in bits]
        rows.append(r[:6] + ['|'.join(order), r[7]])
    added = []
    for (nid, lib, mod), kind in sorted(eboot_imports.items(), key=lambda kv: (kv[0][1], kv[0][0])):
        if (nid, lib, mod) in by_key:
            continue
        name = names.get(nid, '?')
        k = 'Object' if kind == 1 else 'Function'
        if lib == 'libc' or lib == 'libSceFios2':
            phase0 = 'Lle'
        elif f'"{nid}"' in shad_text:
            phase0 = 'Hle'
        else:
            phase0 = 'CommonStub' if k == 'Function' else 'UnresolvedObject'
        sub = subsystem_of_lib.get(lib) or NEW_SUBSYSTEMS.get(lib, 'Other')
        row = [nid, lib, mod, name, k, sub, 'kEboot', phase0]
        rows.append(row)
        added.append(row)
    rows.sort(key=lambda r: (r[1], r[3], r[0]))

    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// GENERATED by tools/gen_import_table.py (inFAMOUS-First-Light-PC-Edition) from the game\'s eboot.bin and\n')
        f.write("// Second Son's import_table.inc (libc.prx / libSceFios2.prx rows) -- do not edit.\n")
        f.write('// Every import of eboot.bin, libc.prx and libSceFios2.prx, keyed exactly like the game imports it.\n')
        f.write('// Columns: nid, library, module, name, kind, subsystem, importers, Phase 0 resolution.\n')
        f.write('// clang-format off\n')
        for r in rows:
            f.write('{"%s", "%s", "%s", "%s", Kind::%s, "%s", %s, Phase0::%s},\n' % tuple(r))
        f.write('// clang-format on\n')
    print(f'{out}: {len(rows)} rows ({len(added)} not in the reference table, '
          f'{len(ref_rows) + len(added) - len(rows)} reference rows dropped)')
    for r in added:
        print('  +', r[1], r[3], r[7])


if __name__ == '__main__':
    main(*sys.argv[1:5])

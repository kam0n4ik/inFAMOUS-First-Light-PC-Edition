//   kCtxInitSequence400 — sceGnmDrawInitToDefaultContextState400.
// Each kInitSequence* starts with a fake CLEAR_STATE preamble (2 dwords) that mimics the context reset the firmware
// sends; the DrawInit* functions skip it and write kClearStateSequence instead. The self-test compares every table with
// the bridge's (src/bridge/shadps4/selftest_gnm.cpp).
